# ------------------------------------------------------- 매칭 유틸

# 공백·문장부호·이모지를 지우고 한글/영문/숫자만 남긴다(초성 ㄱ-ㅎ, 모음 ㅏ-ㅣ 포함).
_NON_WORD = re.compile(r"[^0-9a-z가-힣ㄱ-ㅎㅏ-ㅣ]+")


def normalize(text: str) -> str:
    """띄어쓰기·문장부호를 지워 '씨 발!!'과 '씨발'을 같게 만든다."""
    return _NON_WORD.sub("", text.lower())


def _normalized(words: list[str]) -> list[str]:
    # 중복 제거 + 원래 순서 유지
    return list(dict.fromkeys(normalize(word) for word in words if normalize(word)))


_PROFANITY_N = _normalized(PROFANITY + SEVERE_PROFANITY + CHOSUNG_PROFANITY)
_SEVERE_N = _normalized(SEVERE_PROFANITY)
_CONTEMPT_N = _normalized(CONTEMPT)
_SEXUAL_N = _normalized(SEXUAL_HARASSMENT)
_THREAT_ONLY_N = _normalized(THREAT)
_WEAPON_N = _normalized(WEAPON)
# 고정 안전 절차 트리거는 위협 + 흉기를 함께 본다.
_THREAT_N = _normalized(THREAT + WEAPON)


def _match(text: str, normalized_words: list[str]) -> list[str]:
    haystack = normalize(text)
    if not haystack:
        return []
    return [word for word in normalized_words if word in haystack]


def match_profanity(text: str) -> list[str]:
    return _match(text, _PROFANITY_N)


def match_severe_profanity(text: str) -> list[str]:
    return _match(text, _SEVERE_N)


def match_contempt(text: str) -> list[str]:
    return _match(text, _CONTEMPT_N)


def match_sexual_harassment(text: str) -> list[str]:
    return _match(text, _SEXUAL_N)


def match_threat(text: str) -> list[str]:
    return _match(text, _THREAT_N)


def match_weapon(text: str) -> list[str]:
    return _match(text, _WEAPON_N)


def detect_categories(text: str) -> dict[str, list[str]]:
    """감지된 카테고리별 매칭 단어. 비어 있는 카테고리는 넣지 않는다."""
    found = {
        "흉기": match_weapon(text),
        "위협": _match(text, _THREAT_ONLY_N),
        "성희롱": match_sexual_harassment(text),
        "욕설": match_profanity(text),
        "인격모독": match_contempt(text),
    }
    return {category: words for category, words in found.items() if words}
