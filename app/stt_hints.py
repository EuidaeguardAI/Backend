"""
STT 인식 힌트(프롬프트) 사전.

OpenAI 음성 인식 모델은 `prompt`로 준 어휘를 "이 단어들이 나올 법한 상황"이라는 힌트로 써서
동음이의어를 그쪽으로 기울여 받아쓴다. 매장 현장 용어는 일반 대화에 잘 안 나와서 그냥 두면
자주 틀리는데(예: "유통기한"→"유통 기간", "포스기"→"포스트기", "1+1"→"일 플러스 일"),
미리 넣어 두면 인식률이 눈에 띄게 올라간다.

주의: 프롬프트는 토큰 한도(모델에 따라 대략 224토큰)가 있어 길면 뒤가 잘린다.
그래서 카테고리별로 꼭 필요한 것만 추리고, 최종 문자열 길이도 _MAX_PROMPT_CHARS로 자른다.
"""

# 분쟁의 대부분을 차지하는 핵심 용어 — 가장 앞에 둬서 잘려도 살아남게 한다.
CORE_TERMS: list[str] = [
    "환불", "교환", "반품", "유통기한", "소비기한", "영수증", "결제 취소",
]

# 상품·품질 관련
PRODUCT_TERMS: list[str] = [
    "제조일자", "변질", "상한 우유", "곰팡이", "이물질", "불량품", "파손",
    "개봉", "미개봉", "폐기", "검품", "진열", "재고", "발주",
]

# 결제·정산 관련
PAYMENT_TERMS: list[str] = [
    "카드 결제", "현금영수증", "승인 취소", "포스기", "단말기", "바코드",
    "잔돈", "거스름돈", "계좌이체", "카카오페이", "삼성페이", "기프티콘",
    "상품권", "포인트 적립", "멤버십", "쿠폰", "할인 행사", "원 플러스 원",
    "투 플러스 원", "증정품",
]

# 매장 운영·판매 규정
STORE_TERMS: list[str] = [
    "봉투", "종량제 봉투", "담배", "주류", "신분증", "성인 인증", "미성년자",
    "청소년 보호법", "편의점 택배", "배달 주문", "픽업", "셀프 계산대",
    "키오스크", "계산대", "카운터", "영업시간", "시시티비", "취식", "흡연",
]

# 사람·조직 호칭 (신고/에스컬레이션 발화에서 자주 나온다)
PEOPLE_TERMS: list[str] = [
    "점장님", "사장님", "본사", "가맹점", "고객센터", "아르바이트", "교대",
    "관리자", "경찰", "백십이", "신고",
]

# 폭언 상황을 그대로 받아쓰게 하려는 최소 예시.
# 넣지 않으면 모델이 욕설을 순화하거나 엉뚱한 단어로 바꿔 적어 위험 신호를 놓친다.
# (감지 사전 전체는 app/safety/abusive_lexicon.py)
ABUSE_HINT_TERMS: list[str] = [
    "씨발", "개새끼", "병신", "지랄", "죽여버린다", "가만 안 둬", "뒤진다",
]

_MAX_PROMPT_CHARS = 600


def build_stt_prompt() -> str:
    """음성 인식 모델에 넘길 한국어 힌트 문자열."""
    terms = (
        CORE_TERMS
        + PRODUCT_TERMS
        + PAYMENT_TERMS
        + STORE_TERMS
        + PEOPLE_TERMS
        + ABUSE_HINT_TERMS
    )
    header = (
        "한국 편의점·서비스업 매장에서 고객과 직원이 나누는 한국어 대화입니다. "
        "들린 말을 한국어로 그대로 받아쓰고, 욕설도 순화하지 말고 그대로 적으세요. "
        "자주 나오는 용어: "
    )
    prompt = header + ", ".join(terms)
    return prompt[:_MAX_PROMPT_CHARS]


STT_PROMPT = build_stt_prompt()
